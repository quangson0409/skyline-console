import React, { useState, useMemo } from 'react';
import {
  Breadcrumb,
  Button,
  Card,
  Col,
  Row,
  Space,
  Modal,
  Form,
  Input,
  Radio,
  Tooltip,
  Tag,
  message,
} from 'antd';
import {
  PlusOutlined,
  ReloadOutlined,
  DeleteOutlined,
  KeyOutlined,
  CopyOutlined,
  DownloadOutlined,
} from '@ant-design/icons';
import { useKeypairs } from '@/hooks/useKeypairs';
import { novaApi } from '@/api/nova';
import BaseTable from '@/components/Tables/BaseTable';
import { useTranslation } from '@/core/i18n';

export default function KeypairList() {
  const { t } = useTranslation();
  const { keypairs, loading, refetch, deleteKeypair } = useKeypairs();
  const [selectedRowKeys, setSelectedRowKeys] = useState([]);
  const [magicFilters, setMagicFilters] = useState({});
  const [isModalOpen, setIsModalOpen] = useState(false);
  const [createType, setCreateType] = useState('create');
  const [form] = Form.useForm();

  const filterParams = useMemo(
    () => [
      { name: 'name', label: t('Name') },
      { name: 'fingerprint', label: t('Fingerprint') },
      { name: 'type', label: t('Key Type') },
    ],
    [t]
  );

  const handleCreate = async (values) => {
    try {
      const isCreate = createType === 'create';
      const payload = {
        name: values.name,
        type: 'ssh',
      };
      if (!isCreate && values.publicKey) {
        payload.public_key = values.publicKey.trim();
      }

      const res = await novaApi.createKeypair(payload);
      message.success(t('Keypair created successfully'));

      // If generated by OpenStack, automatically trigger download of .pem private key
      if (isCreate && res?.keypair?.private_key) {
        const blob = new Blob([res.keypair.private_key], { type: 'text/plain;charset=utf-8' });
        const url = URL.createObjectURL(blob);
        const link = document.createElement('a');
        link.href = url;
        link.download = `${values.name}.pem`;
        document.body.appendChild(link);
        link.click();
        document.body.removeChild(link);
        URL.revokeObjectURL(url);
        message.info(t('Private key file downloaded (.pem)'));
      }

      setIsModalOpen(false);
      form.resetFields();
      refetch();
    } catch (err) {
      message.error(err.message || t('Failed to create keypair'));
    }
  };

  const handleDeleteOne = (record) => {
    Modal.confirm({
      title: `${t('Delete Keypair')}: ${record.name}?`,
      content: t('Existing instances using this key will keep working, but this key cannot be selected for new instances.'),
      okText: t('Delete'),
      okType: 'danger',
      cancelText: t('Cancel'),
      onOk: async () => {
        await deleteKeypair(record.name);
        refetch();
      },
    });
  };

  const handleBatchDelete = (keys) => {
    Modal.confirm({
      title: `${t('Batch Delete')} ${keys.length} ${t('Keypairs')}?`,
      content: t('Are you sure you want to delete these keypairs?'),
      okText: t('Delete'),
      okType: 'danger',
      cancelText: t('Cancel'),
      onOk: async () => {
        await Promise.all(keys.map((name) => novaApi.deleteKeypair(name)));
        message.success(t('Keypairs deleted successfully'));
        setSelectedRowKeys([]);
        refetch();
      },
    });
  };

  const rowActions = {
    firstAction: {
      id: 'delete',
      title: t('Delete'),
      isDanger: true,
      onClick: (record) => handleDeleteOne(record),
    },
  };

  const batchActions = [
    {
      id: 'batch-delete',
      label: t('Batch Delete'),
      danger: true,
      onClick: handleBatchDelete,
    },
  ];

  const columns = [
    {
      title: t('Name'),
      dataIndex: 'name',
      key: 'name',
      sorter: (a, b) => (a.name || '').localeCompare(b.name || ''),
      render: (text) => (
        <Space>
          <KeyOutlined style={{ color: '#0068ff' }} />
          <span style={{ fontWeight: 600, color: '#0068ff' }}>{text}</span>
        </Space>
      ),
    },
    {
      title: t('Fingerprint'),
      dataIndex: 'fingerprint',
      key: 'fingerprint',
      render: (fp) => (
        <Space>
          <span style={{ fontFamily: 'monospace', fontSize: 12, color: '#475569' }}>
            {fp || 'N/A'}
          </span>
          {fp && (
            <Tooltip title={t('Copy')}>
              <CopyOutlined
                style={{ cursor: 'pointer', color: '#94a3b8' }}
                onClick={() => {
                  navigator.clipboard.writeText(fp);
                  message.info(t('Copied'));
                }}
              />
            </Tooltip>
          )}
        </Space>
      ),
    },
    {
      title: t('Key Type'),
      dataIndex: 'type',
      key: 'type',
      render: (type) => (
        <Tag color="blue" style={{ textTransform: 'uppercase', fontWeight: 600, borderRadius: 10 }}>
          {type || 'SSH'}
        </Tag>
      ),
    },
  ];

  return (
    <div style={{ maxWidth: 1400, margin: '0 auto' }}>
      {/* Header */}
      <div style={{ marginBottom: 16 }}>
        <Breadcrumb items={[{ title: t('Compute') }, { title: t('Keypairs') }]} style={{ marginBottom: 6 }} />
        <h1 style={{ fontSize: 24, fontWeight: 700, margin: 0, color: '#0f172a' }}>{t('Keypairs')}</h1>
        <p style={{ color: '#64748b', fontSize: 13, margin: '4px 0 0' }}>
          {t('Manage SSH public keys for secure passwordless login to instances.')}
        </p>
      </div>

      {/* KPI Cards */}
      <Row gutter={[16, 16]} style={{ marginBottom: 20 }}>
        <Col xs={24} sm={12}>
          <Card size="small" variant="borderless" style={{ borderRadius: 10, border: '1px solid #e2e8f0' }}>
            <div style={{ color: '#64748b', fontSize: 11, fontWeight: 700 }}>{t('Total Keypairs')}</div>
            <div style={{ fontSize: 22, fontWeight: 800, marginTop: 4, color: '#0068ff' }}>{keypairs.length}</div>
          </Card>
        </Col>
        <Col xs={24} sm={12}>
          <Card size="small" variant="borderless" style={{ borderRadius: 10, border: '1px solid #e2e8f0' }}>
            <div style={{ color: '#64748b', fontSize: 11, fontWeight: 700 }}>SSH Protocol</div>
            <div style={{ fontSize: 22, fontWeight: 800, marginTop: 4, color: '#10b981' }}>RSA / Ed25519</div>
          </Card>
        </Col>
      </Row>

      {/* BaseTable */}
      <BaseTable
        columns={columns}
        dataSource={keypairs}
        loading={loading}
        rowKey="name"
        filterParams={filterParams}
        filters={magicFilters}
        onFilterChange={setMagicFilters}
        onRefresh={refetch}
        primaryAction={{
          id: 'create-keypair',
          label: `${t('Create')} ${t('Keypair')}`,
          icon: <PlusOutlined />,
          onClick: () => setIsModalOpen(true),
        }}
        rowActions={rowActions}
        batchActions={batchActions}
        selectedRowKeys={selectedRowKeys}
        onSelectChange={setSelectedRowKeys}
      />

      {/* Create / Import Keypair Modal */}
      <Modal
        title={`${t('Create')} ${t('Keypair')}`}
        open={isModalOpen}
        onCancel={() => setIsModalOpen(false)}
        footer={null}
        destroyOnHidden
      >
        <Form form={form} layout="vertical" onFinish={handleCreate} initialValues={{ type: 'create' }}>
          <Form.Item label={t('Method')}>
            <Radio.Group
              value={createType}
              onChange={(e) => setCreateType(e.target.value)}
              buttonStyle="solid"
            >
              <Radio.Button value="create">{t('Generate New Keypair')}</Radio.Button>
              <Radio.Button value="import">{t('Import Existing Public Key')}</Radio.Button>
            </Radio.Group>
          </Form.Item>

          <Form.Item
            name="name"
            label={t('Keypair Name')}
            rules={[
              { required: true, message: t('Please input keypair name') },
              { pattern: /^[a-zA-Z0-9._-]+$/, message: t('Only letters, numbers, hyphens, and dots allowed') },
            ]}
          >
            <Input placeholder="my-ssh-key" />
          </Form.Item>

          {createType === 'import' ? (
            <Form.Item
              name="publicKey"
              label={t('Public Key Content')}
              rules={[{ required: true, message: t('Please paste public key content') }]}
              extra="Format: ssh-rsa AAAAB3NzaC1yc2E... user@hostname"
            >
              <Input.TextArea rows={5} placeholder="ssh-rsa AAAAB3NzaC1yc2E..." />
            </Form.Item>
          ) : (
            <div style={{ padding: '12px 14px', background: '#f8fafc', borderRadius: 8, marginBottom: 16, border: '1px solid #e2e8f0', fontSize: 13, color: '#475569' }}>
              <DownloadOutlined style={{ color: '#0068ff', marginRight: 8 }} />
              OpenStack sẽ tự động tạo cặp khóa RSA 2048-bit và tải tệp khóa riêng <b>.pem</b> về máy tính của bạn ngay sau khi tạo.
            </div>
          )}

          <div style={{ display: 'flex', justifyContent: 'flex-end', gap: 10, marginTop: 16 }}>
            <Button onClick={() => setIsModalOpen(false)}>{t('Cancel')}</Button>
            <Button type="primary" htmlType="submit" style={{ background: '#0068ff' }}>
              {createType === 'create' ? t('Create and Download') : t('Import')}
            </Button>
          </div>
        </Form>
      </Modal>
    </div>
  );
}
